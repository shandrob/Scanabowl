/** Clean footnote superscripts, Royal Canin L.I.P. boilerplate, and stray decimal-comma digits. */
function cleanRaw(raw: string): { base: string; dosage: string } {
  let s = raw
    .replace(/\u0308/g, "ï") // combining diaeresis
    .replace(/i\u0308/g, "ï")
    .replace(/\s*l\.i\.p\.\s*:.*$/i, "")
    .replace(/[¹²³⁴⁵⁶⁷⁸⁹⁰]+/g, "")
    .replace(/\s+\d$/g, "") // stray trailing single digit ("zalmolie 0", "rijst 1")
    .replace(/\s+/g, " ")
    .trim();

  let dosage = "";
  const dm = s.match(/\s+(\d[\d.,]*\s*(?:mg|g|iu|ie|kve|cfu)\/kg)$/i);
  if (dm) {
    dosage = ` (${dm[1]})`;
    s = s.slice(0, s.length - dm[0].length).trim();
  }
  return { base: s, dosage };
}

function lookupCore(norm: string, lang: Locale): string | null {
  const idx = LANG_IDX[lang];
  const hit = DICT[norm];
  if (hit) return hit[idx];

  // Trailing "extract" / "-extract"
  const extMatch = norm.match(/^(.+?)(?:\s+|-)(?:extract|extrakt)$/i);
  if (extMatch) {
    const inner = lookupCore(extMatch[1].trim(), lang);
    if (inner) {
      return lang === "nl"
        ? `${inner}-extract`
        : lang === "en"
          ? `${inner} extract`
          : lang === "de"
            ? `${inner}-Extrakt`
            : `extrait de ${inner}`;
    }
  }

  // Prefix modifiers ("gedroogde X", "verse X", etc.)
  for (const mod of PREFIX_MODIFIERS) {
    const m = norm.match(mod.re);
    if (m) {
      const inner = lookupCore(m[1].trim(), lang);
      if (inner) return mod.wrap(inner, lang);
    }
  }

  // Compound "X en Y" or "X and Y"
  const andParts = norm.split(/\s+(?:en|and|&)\s+/i);
  if (andParts.length === 2) {
    const left = lookupCore(andParts[0].trim(), lang);
    const right = lookupCore(andParts[1].trim(), lang);
    if (left && right) {
      const conj = lang === "nl" ? "en" : lang === "en" ? "and" : lang === "de" ? "und" : "et";
      return `${left} ${conj} ${right}`;
    }
  }

  return null;
}

/**
 * Translate a raw ingredient label token into the active page locale (`nl`, `en`, `de`, `fr`).
 * Falls back to the cleaned original string when an uncommon/proprietary phrase is not in the dictionary.
 */
export function translateIngredient(raw: string, lang: Locale): string {
  const { base, dosage } = cleanRaw(raw);
  if (!base) return raw;
  const norm = base.toLowerCase();
  const translated = lookupCore(norm, lang);
  if (translated) return `${translated}${dosage}`;
  return `${base}${dosage}`;
}
